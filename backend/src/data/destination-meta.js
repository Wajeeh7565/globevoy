function cleanOriginInput(input) {
  return String(input || '').trim().toLowerCase().replace(/\s*\([^)]*\)\s*/g, '');
}

function resolveOrigin(input) {
  const raw = cleanOriginInput(input);
  if (!raw || ORIGIN_PLACEHOLDERS.has(raw)) return null;
  const code = ORIGIN_ALIASES[raw] || raw.toUpperCase();
  return ORIGINS[code] || null;
}

function normalizeOrigin(input) {
  // Legacy fallback helper for internal/mock callers. Public recommendations
  // use resolveOrigin() so missing or unknown origins stay user-controlled.
  return resolveOrigin(input || 'YTO') || ORIGINS.YTO;
}

function getDestination(codeOrCity) {
  const raw = String(codeOrCity || '').trim();
  const upper = raw.toUpperCase();
  if (DESTINATIONS[upper]) return DESTINATIONS[upper];
  return Object.values(DESTINATIONS).find(dest => dest.city.toLowerCase() === raw.toLowerCase()) || null;
}

